    /**
     * Resolves the matching HD image path for any product object.
     * Follows strict hierarchy:
     * 1. Exact Part Number match
     * 2. Subcategory match via keywords and taxonomy
     * 3. Category match fallback
     * 4. Default HD category image
     */
    function getProductImage(product) {
        if (!product) return 'assets/groz images/WhatsApp Image 2026-10-29 at 12.57.41 PM.jpeg';

        // 1. Exact Part Number match
        const partNo = (product.partNo || '').trim();
        if (partNo && EXACT_PART_MAPPINGS[partNo]) {
            return EXACT_PART_MAPPINGS[partNo];
        }

        // If product already has a verified groz images path, return it
        if (product.image && (product.image.includes('assets/products/') || product.image.includes('assets/groz images/'))) {
            return product.image;
        }

        const rawCat = (product.category || '').toUpperCase();
        const searchTarget = ((product.productName || '') + ' ' + (product.subcategory || '') + ' ' + partNo).toLowerCase();

        // 2. Search taxonomy in CATEGORY_DEFINITIONS
        const catDefs = window.CATEGORY_DEFINITIONS || [];
        for (const cat of catDefs) {
            const isCatMatch = (cat.rawCategories && cat.rawCategories.some(rc => rc.toUpperCase() === rawCat)) ||
                               cat.name.toUpperCase() === rawCat;
            if (isCatMatch) {
                if (cat.subs && cat.subs.length > 0) {
                    for (const sub of cat.subs) {
                        if (sub.keywords && sub.keywords.some(kw => searchTarget.includes(kw.toLowerCase()))) {
                            return sub.image;
                        }
                    }
                }
                return cat.image;
            }
        }

        return 'assets/groz images/WhatsApp Image 2026-10-29 at 12.57.41 PM.jpeg';
    }

    /**
     * Returns the HD image for a main category by ID (c1 to c7, c-spares) or name
     */
    function getCategoryImage(catIdOrName) {
        const needle = (catIdOrName || '').toLowerCase();
        const mapping = GROZ_IMAGE_MAPPINGS.find(m => 
            m.type === 'category' && (
                (m.categoryId && m.categoryId.toLowerCase() === needle) ||
                (m.category && m.category.toLowerCase() === needle)
            )
        );
        return mapping ? mapping.imagePath : 'assets/groz images/WhatsApp Image 2026-10-29 at 12.57.41 PM.jpeg';
    }

    /**
     * Returns the HD image for a subcategory by subId (e.g. c1-1) or subcategory name
     */
    function getSubcategoryImage(subIdOrName) {
        const needle = (subIdOrName || '').toLowerCase();
        const mapping = GROZ_IMAGE_MAPPINGS.find(m => 
            m.type === 'subcategory' && (
                (m.subcategoryId && m.subcategoryId.toLowerCase() === needle) ||
                (m.subcategory && m.subcategory.toLowerCase() === needle) ||
                (m.labelOnImage && m.labelOnImage.toLowerCase() === needle)
            )
        );
        return mapping ? mapping.imagePath : null;
    }

    // Expose to global window scope
    window.GROZ_IMAGE_MAPPINGS = GROZ_IMAGE_MAPPINGS;
    window.EXACT_PART_MAPPINGS = EXACT_PART_MAPPINGS;
    window.getProductImage = getProductImage;
    window.getCategoryImage = getCategoryImage;
    window.getSubcategoryImage = getSubcategoryImage;

